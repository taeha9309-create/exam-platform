/** 서버 오류 코드를 한국어 문구로 바꾼다. 모르는 코드는 일반 오류 문구. */
export function errorText(code: string): string {
  const map: Record<string, string> = t.errors;
  return Object.prototype.hasOwnProperty.call(map, code) ? map[code]! : t.errors.UNKNOWN;
}
